#!/usr/bin/env python3
"""Build the reviewer package for the indexer-hardening guide (guide/review/).

Publication of the guide waits for a review by a stellar-core or platform engineer. This script builds what we
send them, from the repository:

- claims.csv      the claim-to-source map exported from guide/claims.yaml, one row per claim, with a link to
                  every cited source line at its pinned commit;
- unverified.md   what is not established, what the published table holds back, and which published lines rest
                  on a code reference alone (from corpus/fields.yaml and the generated blocks of the guide page);
- request.md      the request text, rendered from request.template.md with the current counts and the questions
                  of questions.md (a draft for a maintainer to send; this script sends nothing);
- README.md       what the package is, its counts per guide section, and how a review is recorded;
- high-risk.md    the claims to check first: what the guide says stellar-core does not validate;
- ../VERIFICATION.md  the authors' verification report (verification.py, from verification.template.md), which
                  reads code-refs.tsv: whether every cited code line exists at its pinned commit. Only
                  `build.py --resolve-refs --src core=PATH --src xdr=PATH --src env=PATH` needs the upstream
                  clones; it rewrites code-refs.tsv.

Inputs it checks: every claim ID and row ID that questions.md names exists; every placeholder of the template
is filled; every corpus entry the guide, the checklist or claims.yaml cites exists in corpus/index.json
(scripts/py/check_guide_entries.py), so a reviewer is never sent to an entry that has no bytes. Usage: build.py [--check]. With --check it writes nothing and exits 1 when a file differs from a fresh
build. Usage: build.py --resolve-refs --src NAME=PATH… rewrites code-refs.tsv. Needs PyYAML (the repository's .venv)."""
import csv, importlib.util, io, os, re, string, sys
import yaml

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import verification  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", ".."))
CLAIMS = os.path.join(ROOT, "guide", "claims.yaml")
FIELDS = os.path.join(ROOT, "corpus", "fields.yaml")
PAGE = os.path.join(ROOT, "guide", "indexer-hardening.mdx")
QUESTIONS = os.path.join(HERE, "questions.md")
TEMPLATE = os.path.join(HERE, "request.template.md")
CHECKLIST = os.path.join(ROOT, "guide", "checklist.mdx")
VTEMPLATE = os.path.join(HERE, "verification.template.md")
REFS_TSV = os.path.join(HERE, "code-refs.tsv")

GENERATED = "<!-- Generated by guide/review/build.py; edit its sources, not this file. -->\n\n"
CODE_RE = re.compile(r"^(?:(env|xdr):)?([\w./-]+):(\d[\d\s,-]*)$")


def load(path):
    with open(path, encoding="utf-8") as f:
        return yaml.safe_load(f)


def read(path):
    with open(path, encoding="utf-8") as f:
        return f.read()


class Pins:
    def __init__(self, fields):
        p = fields["pins"]
        self.base = {
            None: "https://github.com/stellar/stellar-core/blob/%s/" % p["stellar_core"]["tag"],
            "xdr": "https://github.com/stellar/stellar-xdr/blob/%s/" % p["stellar_xdr"]["commit"],
            "env": "https://github.com/stellar/rs-soroban-env/blob/%s/" % p["soroban_env_host"]["commit"],
        }

    def links(self, ref):
        """Links for a code reference `[env:|xdr:]path:1-2, 5`; several references may be joined with `;`.
        A reference in another form is returned as it is."""
        out = []
        for seg in ref.split(";"):
            m = CODE_RE.match(seg.strip())
            if not m:
                out.append(seg.strip())
                continue
            prefix, path, ranges = m.groups()
            for r in ranges.split(","):
                a, _, b = r.strip().partition("-")
                out.append(self.base[prefix] + path + "#L" + a + ("-L" + b if b else ""))
        return out


def source_text(s, pins):
    if s["kind"] == "code":
        return "code: " + ", ".join(pins.links(s["ref"]))
    return "%s: %s%s" % (s["kind"], s["ref"], " (%s)" % s["at"] if s.get("at") else "")


def claims_csv(claims, pins):
    buf = io.StringIO()
    w = csv.writer(buf, lineterminator="\n")
    w.writerow(["claim_id", "guide_anchor", "kind", "verification", "reviewer_status", "reviewer_note", "fields",
                "corpus_entries", "sources", "sentence"])
    for c in claims:
        w.writerow([c["claim_id"], c["guide_anchor"], c["kind"], c["verification"], c["reviewer_status"],
                    c.get("reviewer_note", ""), " ".join(c.get("fields", [])), " ".join(c.get("corpus_entries", [])),
                    "; ".join(source_text(s, pins) for s in c["source"]), " ".join(c["sentence"].split())])
    return buf.getvalue()


def page_blocks(page):
    """Published line IDs and withheld lines of the generated field table in the guide page."""
    published, withheld, inside = [], [], False
    for line in page.split("\n"):
        if line.startswith("{/* BEGIN GENERATED: fields "):
            inside = True
        elif line.startswith("{/* END GENERATED"):
            inside = False
        elif inside and line.startswith("| VF-"):
            published.append(line[2:].split(" |", 1)[0])
        elif inside and line.startswith("- VF-"):
            withheld.append(line[2:])
    return published, withheld


def section_items(page, anchor):
    """List items of the page section with this anchor, claim tags removed."""
    out, inside = [], False
    for line in page.split("\n"):
        if re.match(r"^#{2,6} ", line):
            inside = line.rstrip().endswith("{#%s}" % anchor)
        elif inside and line.startswith("- "):
            out.append(re.sub(r"\s*\{/\*.*?\*/\}", "", line[2:]).strip())
    return out


def lines_of(fields):
    """Every line of the field table: (id, row, part or None)."""
    for r in fields["fields"]:
        if r.get("parts"):
            for p in r["parts"]:
                yield p["id"], r, p
        else:
            yield r["id"], r, None


def md_cell(text):
    return " ".join(str(text).split()).replace("|", "\\|")


def unverified_md(fields, page, pins):
    published, withheld = page_blocks(page)
    out = [GENERATED, "# What is not established yet\n\n",
           "Built from the field table source and the guide page. A reviewer's confirmation matters most for the "
           "lines in the last section: they are published on a code reference alone.\n\n"]

    open_parts = [(i, r, p) for i, r, p in lines_of(fields)
                  if (p or r)["verification"] == "unverified" or (p or r)["status"] == "undetermined"]
    out.append("## Parts not established\n\n")
    out.append("Left out of the published table until they are established. The reason is the row's own note.\n\n")
    out.append("| Line | Field | Aspect | Why it is open |\n| --- | --- | --- | --- |\n")
    for i, r, p in open_parts:
        out.append("| %s | %s | %s | %s |\n" % (i, md_cell(r["field"]), md_cell(p["aspect"] if p else ""),
                                                 md_cell(" ".join(r.get("unverified_parts", [])))))
    inner = [r for r in fields["fields"] if r.get("unverified_parts") and r["verification"] != "unverified"]
    if inner:
        out.append("\n## Open points inside published rows\n\n")
        out.append("The row is published; one detail of it is not established.\n\n")
        for r in inner:
            out.append("- %s %s: %s\n" % (r["id"], r["field"], " ".join(r["unverified_parts"])))

    out.append("\n## Lines held back from the published table\n\n")
    out.append("As the guide page lists them under each group of the table.\n\n")
    out.extend("- %s\n" % w for w in withheld)

    code_only = []
    for i, r, p in lines_of(fields):
        if i in published and (p or r)["verification"] == "code_reference":
            code_only.append((i, r, p))
    out.append("\n## Lines published on a code reference alone\n\n")
    out.append("%d of the %d published lines. Each verdict rests on reading the code at the pinned commit; no "
               "executed ledger or probe shows it yet.\n\n" % (len(code_only), len(published)))
    out.append("| Line | Field | Status | Code |\n| --- | --- | --- | --- |\n")
    for i, r, p in code_only:
        refs = []
        for chk in r.get("core_checks", []):
            refs += ["[%s](%s)" % (u.rsplit("/", 1)[-1], u) if u.startswith("https://") else md_cell(u)
                     for u in pins.links(chk["code_ref"])]
        field = r["field"] + (": " + p["aspect"] if p else "")
        out.append("| %s | %s | %s | %s |\n" % (i, md_cell(field), (p or r)["status"].replace("_", " "),
                                                 ", ".join(refs)))

    items = section_items(page, "not-yet-established")
    out.append("\n## Statements the guide marks as not yet established\n\n")
    out.extend("- %s\n" % it for it in items)
    return "".join(out), len(code_only), len(withheld)


def questions(claim_ids, row_ids):
    text = read(QUESTIONS)
    errors = []
    for c in sorted(set(re.findall(r"\bC-\d{3,4}\b", text))):
        if c not in claim_ids:
            errors.append("questions.md names %s, which is not a claim in guide/claims.yaml" % c)
    for v in sorted(set(re.findall(r"\bVF-\d{2,3}[a-z]?\b", text))):
        if v not in row_ids:
            errors.append("questions.md names %s, which is not a row or part in corpus/fields.yaml" % v)
    # Each question: "N. **Title** body", continued on indented lines; the Rows/Claims line is for us.
    items = []
    for m in re.finditer(r"^(\d+)\. (\*\*.+?\*\*.*?)(?=^\d+\. |\Z)", text, re.M | re.S):
        body = " ".join(m.group(2).split())
        body = re.sub(r"\s*(Rows|Claims): .*$", "", body)
        items.append("%s. %s" % (m.group(1), body))
    if not items:
        errors.append("questions.md has no numbered questions with a bold title")
    return items, errors


def readme(claims, code_only, withheld, n_questions, n_lines):
    count = lambda pred: sum(1 for c in claims if pred(c))
    groups = {}
    for c in claims:
        a = c["guide_anchor"] or "(opening, before the first section)"
        a = "#vf-nn (field-table rows)" if a.startswith("#vf-") else a
        groups.setdefault(a, []).append(c)
    rows = []
    for a, cs in sorted(groups.items(), key=lambda kv: (not kv[0].startswith("#vf"), kv[0])):
        n = lambda k, v: sum(1 for c in cs if c[k] == v)
        rows.append("| `%s` | %d | %d | %d | %d | %d | %d |\n" % (
            a, len(cs), n("kind", "fact"), n("kind", "recommendation"), n("verification", "executed"),
            n("verification", "code_reference"), n("reviewer_status", "unreviewed")))
    statuses = ", ".join("%s %d" % (s, count(lambda c, s=s: c["reviewer_status"] == s))
                         for s in ("unreviewed", "confirmed", "corrected", "disputed"))
    return "".join([
        GENERATED,
        "# Review package\n\n",
        "The guide (`guide/indexer-hardening.mdx` and `guide/checklist.mdx`) is published only after a stellar-core "
        "or platform engineer has reviewed what it says about stellar-core. This folder is what we give the "
        "reviewer.\n\n",
        "| File | What it is |\n| --- | --- |\n",
        "| `request.md` | The request text, a draft for a maintainer to send; nothing is sent from here |\n",
        "| `questions.md` | The %d questions we ask, each naming the claims and rows it bears on |\n" % n_questions,
        "| `claims.csv` | The claim-to-source map: every claim of `guide/claims.yaml` with its sentence, kind, "
        "verification, review status and a link to each cited source line |\n",
        "| `unverified.md` | What is not established, what the published table holds back, and the lines "
        "published on a code reference alone |\n",
        "| `high-risk.md` | The claims to check first: what the guide says stellar-core does not validate |\n",
        "| `../VERIFICATION.md` | The authors' verification report: how each claim was checked and what is still open "
        "(built from `verification.template.md` by `verification.py`; `code-refs.tsv` records that each cited code "
        "line exists at its pinned commit) |\n",
        "| `build.py`, `request.template.md` | How the generated files are built |\n\n",
        "## Counts\n\n",
        "- %d claims: %d facts, %d recommendations.\n" % (
            len(claims), count(lambda c: c["kind"] == "fact"), count(lambda c: c["kind"] == "recommendation")),
        "- Verification: %d executed, %d code reference.\n" % (
            count(lambda c: c["verification"] == "executed"), count(lambda c: c["verification"] == "code_reference")),
        "- Review status: %s.\n" % statuses,
        "- Field table: %d published lines, %d of them on a code reference alone; %d lines held back.\n\n" % (
            n_lines, code_only, withheld),
        "| Guide section | Claims | Facts | Recommendations | Executed | Code reference | Unreviewed |\n",
        "| --- | --- | --- | --- | --- | --- | --- |\n",
        *rows,
        "\n## Recording the review\n\n",
        "Each answer changes one claim in `guide/claims.yaml`: `reviewer_status` becomes `confirmed`, `disputed` or "
        "`corrected`, and `reviewer_note` records what the reviewer said. A corrected claim changes the guide "
        "sentence and its record together. The docs pull request is opened only when no claim is `disputed` and "
        "every fact claim is `confirmed` or `corrected`.\n\n",
        "## Building\n\n",
        "`.venv/bin/python guide/review/build.py` rebuilds the generated files; `--check` (run by "
        "`make verify-guide`) fails when one is out of date. The reviewer can also run `make verify-guide`, which "
        "checks the field table against the corpus manifest and the guide against its claim map.\n",
    ])


NEGATIVE_RE = re.compile(r"\b(not|never|no|without|only)\b[^.|]*\b(check|checks|checked|validat\w*|verif\w*|"
                         r"consum\w*|accept\w*|admit\w*|authenticat\w*|stripped|charged)\b", re.I)


def high_risk(claims, fields):
    """The claims to review first: what the guide says stellar-core does NOT validate. Derived, not hand-picked:
    (1) the verdict of every field-table line whose status is passed through; (2) every other fact claim tied to
    such a line, and every page fact whose sentence says core does not check, verify, consume or accept something.
    Within each list, claims on a code reference alone come first. Returns (verdicts, others), each ordered."""
    status = {}
    for r in fields["fields"]:
        status[r["id"]] = r["status"]
        for p in r.get("parts", []):
            status[p["id"]] = p["status"]
    passed = {k for k, v in status.items() if v == "passed_through"}
    facts = [c for c in claims if c["kind"] == "fact"]
    tied = lambda c: bool(set(c.get("fields") or []) & passed)
    verdicts = [c for c in facts if tied(c) and re.search(r"pass(es|ed) through", c["sentence"])]
    seen = {c["claim_id"] for c in verdicts}
    others = [c for c in facts if c["claim_id"] not in seen and (
        tied(c) or (int(c["claim_id"][2:]) >= 6000 and NEGATIVE_RE.search(c["sentence"])))]
    order = lambda cs: sorted(cs, key=lambda c: (c["verification"] != "code_reference", c["claim_id"]))
    return order(verdicts), order(others)


def high_risk_md(claims, fields):
    verdicts, others = high_risk(claims, fields)
    row = lambda c: "| %s | %s | %s | %s |\n" % (c["claim_id"], c["verification"].replace("_", " "),
                                                ", ".join(c.get("fields") or []) or "—", md_cell(c["sentence"]))
    head = "| Claim | Verification | Field-table lines | Sentence |\n| --- | --- | --- | --- |\n"
    return "".join([
        GENERATED,
        "# Highest-risk claims\n\n",
        "What the guide says stellar-core does NOT validate. These are the hardest statements to establish from "
        "code: a check can sit in a file or a stage the source links do not cover, and no ledger can show that a "
        "check is absent everywhere. Both lists are derived from "
        "`guide/claims.yaml` and `corpus/fields.yaml`, so they follow every change; claims on a code reference "
        "alone come first in each.\n\n",
        "## 1. Passed-through verdicts of the field table (%d)\n\n" % len(verdicts), head,
        *map(row, verdicts),
        "\n## 2. Other statements that core does not check, verify, consume or accept something (%d)\n\n"
        % len(others), head, *map(row, others),
    ])


def build():
    claims = load(CLAIMS)["claims"]
    fields = load(FIELDS)
    page = read(PAGE)
    pins = Pins(fields)
    row_ids = {i for i, _, _ in lines_of(fields)} | {r["id"] for r in fields["fields"]}
    titles, errors = questions({c["claim_id"] for c in claims}, row_ids)
    unverified, code_only, withheld = unverified_md(fields, page, pins)
    published, _ = page_blocks(page)
    values = {
        "claims": len(claims),
        "facts": sum(c["kind"] == "fact" for c in claims),
        "recommendations": sum(c["kind"] == "recommendation" for c in claims),
        "executed": sum(c["verification"] == "executed" for c in claims),
        "code_reference": sum(c["verification"] == "code_reference" for c in claims),
        "rows": len(published) + withheld,
        "code_only_rows": code_only,
        "withheld": withheld,
        "questions": "\n".join(titles),
    }
    try:
        request = string.Template(read(TEMPLATE)).substitute(values)
    except (KeyError, ValueError) as e:
        errors.append("request.template.md: unknown or malformed placeholder %s" % e)
        request = ""
    request = re.sub(r"\A<!--.*?-->\n\n", "", request, flags=re.S)
    verdicts, others = high_risk(claims, fields)
    gce = checker()
    ids, groups = gce.existing(ROOT)
    report, verrors = verification.build_report({
        "claims": claims, "fields": fields, "page": page, "checklist": read(CHECKLIST), "pins": pins, "root": ROOT,
        "code_re": CODE_RE, "refs": verification.read_refs_tsv(REFS_TSV), "verdicts": verdicts, "others": others,
        "unverified": (code_only, published, withheld), "withheld_lines": page_blocks(page)[1], "questions": titles,
        "index": load(os.path.join(ROOT, "corpus", "index.json"))["entries"], "groups": groups,
        "ids_exist": lambda cid: gce.exists(cid, ids), "template": read(VTEMPLATE)})
    errors += verrors
    files = {
        "../VERIFICATION.md": GENERATED.replace("guide/review/build.py", "guide/review/build.py from "
                                                "guide/review/verification.template.md") + report,
        "claims.csv": claims_csv(claims, pins),
        "unverified.md": unverified,
        "request.md": GENERATED + request,
        "README.md": readme(claims, code_only, withheld, len(titles), len(published)),
        "high-risk.md": high_risk_md(claims, fields),
    }
    return files, errors


def checker():
    """scripts/py/check_guide_entries.py as a module."""
    path = os.path.join(ROOT, "scripts", "py", "check_guide_entries.py")
    spec = importlib.util.spec_from_file_location("check_guide_entries", path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def entry_errors():
    """Citations of corpus entries that do not exist (scripts/py/check_guide_entries.py)."""
    return checker().problems(ROOT)[0]


def resolve(argv):
    """--resolve-refs: write code-refs.tsv from clones of stellar-core, stellar-xdr and rs-soroban-env, given as
    --src core=PATH --src xdr=PATH --src env=PATH or XDRCHECK_SRC_CORE / _XDR / _ENV (the same as
    scripts/py/check_fields.py --print-refs). Each clone must hold the commit corpus/fields.yaml pins."""
    srcs = {k: os.environ.get("XDRCHECK_SRC_" + k.upper()) for k in ("core", "xdr", "env")}
    for i, a in enumerate(argv):
        if a == "--src" and i + 1 < len(argv):
            k, _, val = argv[i + 1].partition("=")
            srcs[k] = val
    missing = [k for k, val in srcs.items() if not val]
    if missing:
        print("FAIL --resolve-refs needs a clone for %s (--src NAME=PATH)" % ", ".join(missing))
        return 1
    data = verification.resolve_refs(load(CLAIMS)["claims"], load(FIELDS), CODE_RE, srcs)
    with open(REFS_TSV, "w", encoding="utf-8", newline="\n") as f:
        f.write(data)
    bad = [line for line in data.split("\n")[1:] if line and not line.endswith("\tok")]
    print("code-refs.tsv: %d references, %d not found" % (data.count("\n") - 1, len(bad)))
    for line in bad:
        print("FAIL " + line)
    return 1 if bad else 0


def main(argv):
    if "--resolve-refs" in argv[1:]:
        return resolve(argv[1:])
    check = "--check" in argv[1:]
    files, errors = build()
    errors += entry_errors()
    for e in errors:
        print("FAIL " + e)
    if errors:
        return 1
    bad = 0
    for name, data in sorted(files.items()):
        path = os.path.normpath(os.path.join(HERE, name))
        if check:
            current = read(path) if os.path.exists(path) else None
            if current != data:
                print("FAIL %s is %s; run guide/review/build.py" % (
                    os.path.relpath(path, ROOT), "missing" if current is None else "out of date"))
                bad += 1
        else:
            with open(path, "w", encoding="utf-8", newline="\n") as f:
                f.write(data)
    print("review package: %d files %s" % (len(files), "checked" if check else "written") +
          ("" if not bad else ", %d out of date" % bad))
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
