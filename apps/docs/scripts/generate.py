#!/usr/bin/env python3
"""Generate the reference pages of the documentation site from the repository, so the site cannot drift from it.

    python3 apps/docs/scripts/generate.py            # write every generated page
    python3 apps/docs/scripts/generate.py --check    # exit 1 when a generated page is stale or a page breaks a rule
    python3 apps/docs/scripts/generate.py --capture-help BIN_DIR   # refresh apps/docs/data/help/*.txt first

What is generated, and from what:

- `reference/cli.mdx`: every command on one page, from `docs/cli.md` (whose `--help` blocks
  `scripts/py/check_cli_reference.py` keeps equal to the built binaries) and, for the two tools that file does
  not cover, from `apps/docs/data/help/*.txt` (captured with `--capture-help`).
- `reference/make-targets.mdx`, the specifications under `reference/` and the guides under `guides/`, each from
  its Markdown source in `docs/`, `go/adapters/`, `examples/` or `crates/` (the table PAGES below). A page may
  append further sources as sections (`Part`), and may start from a hand-written template
  `apps/docs/data/*.mdx.in` instead of a Markdown source.
- `reference/lint-rules.mdx`: every xdrlint rule on one page, a section per rule ID, from `lint/docs/*.md`.
- `caps/overview.mdx`: the CAP, pattern and ledger relation, a section per coverage row, from
  `corpus/index.json`, `corpus/coverage.json` and the compact data file `apps/docs/data/cap-prevalence.json`
  (written by `cap_prevalence.py`).
- `hardening/verification.mdx` from `guide/VERIFICATION.md` (itself generated by `guide/review/build.py`).
- `results/*` and `start/read-an-entry.mdx` from `evidence/results/*.json`, `evidence/mainnet-scan/` (its README
  and `entry-prevalence.json`) and the corpus. `index.mdx` from the template `apps/docs/data/index.mdx.in`, whose
  `@@name@@` figures come from the same files as the results pages.

Hand-written pages (the quickstart, `start/for-sdk-maintainers.mdx`, `start/for-indexers.mdx`, `architecture/`
and `hardening/overview.mdx`) are never touched.

`--check` also checks every internal link of every page: the page exists, the anchor is a heading of it (as
Mintlify slugs headings), and every page is in the navigation of `docs.json`.

Conversion: Markdown becomes MDX (frontmatter from the first heading; `{`, `}` and `<` escaped outside code; HTML
comments dropped); links between converted pages become site routes, links to other repository files become
plain paths; the repository's module path becomes `OWNER/REPO`. Pages other than the findings table
(`results/findings.mdx`, FINDINGS_PAGES) carry no acceptance or findings vocabulary: a sentence, list item or
table row that holds it is left out, a section whose heading holds it is left out, and so are the flags that
serve that process in `--help` blocks. Pages also carry no decoder nesting-depth figures. A final scan fails the
run when any page still holds such text.

The command names live in TOOLS below, in one place.
"""

