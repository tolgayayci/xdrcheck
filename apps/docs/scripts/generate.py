def escape_line_block(text: str) -> str:
    return "\n".join(escape_line(l) for l in text.split("\n"))


COMPONENT_LINE = re.compile(r"^\s*</?(?:AccordionGroup|Accordion|Columns|Card|CardGroup|Note|Info|Warning|Tip|Steps|Step)\b[^>]*>\s*$")


def escape_mdx(text: str) -> str:
    """escape_line_block, but lines that are only a built-in component tag pass through."""
    return "\n".join(l if COMPONENT_LINE.match(l) else escape_line(l) for l in text.split("\n"))


