def help_sections(text: str) -> list[tuple[str, str]]:
    """(command, section text) for every `#### `<command> --help`` section."""
    out = []
    parts = re.split(r"(?m)^#### `([^`]+?) (?:--help|-h)`\s*$", text)
    for i in range(1, len(parts), 2):
        out.append((parts[i].strip(), parts[i + 1].strip()))
    return out


def help_block(cmd: str, body: str) -> str:
    return f"### `{cmd} --help`\n\n{body.strip()}\n"


def clean_help(body: str) -> str:
    body = drop_help_flags(body, ["overlay", "pending", "findings", "finding"])
    body = "\n".join(l for l in body.split("\n") if not re.match(r"^  (findings|overlay)\s{2,}", l))
    body = body.replace("|sdk-regression|", "|").replace("|scoreboard|siblings", "")
    body = "\n".join(l for l in body.split("\n") if not re.match(r"^  cut-slices\s", l))
    body = body.replace(" (default <overlay>/corpus)", "")
    body = re.sub(r" \(default `\$XDRCHECK_OVERLAY/[^`]*`\)", "", body)
    return body


