def bad(text: str, public: bool = True) -> str | None:
    rules = (PROCESS if public else []) + DEPTH + INTERNAL
    for rx in rules:
        m = rx.search(text)
        if m:
            return m.group(0)
    return None


# ------------------------------------------------------------------ Markdown helpers

FENCE_RE = re.compile(r"^(\s*)(`{3,}|~{3,})")


def headings(lines: list[str]) -> list[tuple[int, int, str]]:
    out, fence = [], None
    for i, line in enumerate(lines):
        m = FENCE_RE.match(line)
        if m:
            mark = m.group(2)
            if fence is None:
                fence = mark[0] * len(mark)
            elif mark.startswith(fence):
                fence = None
            continue
        if fence is None:
            h = re.match(r"^(#{1,6})\s+(.*?)\s*$", line)
            if h:
                out.append((i, len(h.group(1)), h.group(2)))
    return out


def section_span(lines: list[str], title_re: str) -> tuple[int, int] | None:
    hs = headings(lines)
    for n, (i, level, text) in enumerate(hs):
        if re.fullmatch(title_re, text):
            end = len(lines)
            for j, lv, _ in hs[n + 1:]:
                if lv <= level:
                    end = j
                    break
            return i, end
    return None


def cut_sections(text: str, titles: list[str], src: str) -> tuple[str, list[str]]:
    lines = text.split("\n")
    removed = []
    for t in titles:
        span = section_span(lines, t)
        if span is None:
            sys.exit(f"generate: {src}: no section matching {t!r} (the source changed; update the script)")
        i, j = span
        removed.append("\n".join(lines[i:j]).rstrip() + "\n")
        del lines[i:j]
    return "\n".join(lines), removed


def split_at(text: str, title_re: str, src: str) -> tuple[str, str]:
    lines = text.split("\n")
    span = section_span(lines, title_re)
    if span is None:
        sys.exit(f"generate: {src}: no section matching {title_re!r}")
    return "\n".join(lines[: span[0]]), "\n".join(lines[span[0]:])


def sub(text: str, pattern: str, repl: str, src: str, count: int = 0, flags: int = 0) -> str:
    new, n = re.subn(pattern, repl, text, count=count, flags=flags)
    if n == 0:
        sys.exit(f"generate: {src}: pattern not found: {pattern!r} (the source changed; update the script)")
    return new


def drop_help_flags(text: str, names: list[str]) -> str:
    """In --help blocks, drop the named flags (the flag line and its indented continuation)."""
    flag_re = re.compile(r"^(\s+)-{1,2}(%s)\b" % "|".join(map(re.escape, names)))
    out, skip = [], None
    for line in text.split("\n"):
        if skip is not None:
            stripped = line.lstrip(" \t")
            indent = len(line) - len(stripped)
            if stripped and (indent > skip or line.startswith("    \t")) and not re.match(r"\s+-{1,2}\w", line):
                continue
            skip = None
        m = flag_re.match(line)
        if m:
            skip = len(m.group(1))
            continue
        out.append(line)
    return "\n".join(out)


SENTENCE_RE = re.compile(r"(?<=[.;!?])\s+(?=[A-Z`(\[*])")


def scrub(text: str, public: bool = True) -> str:
    """Leave out what a public page must not carry: sections, table rows, list items and sentences."""
    lines = text.split("\n")
    # 1. sections whose heading carries it
    while True:
        hit = next(((i, lv) for i, lv, t in headings(lines) if bad(t, public)), None)
        if hit is None:
            break
        i, level = hit
        end = len(lines)
        for j, lv, _ in headings(lines):
            if j > i and lv <= level:
                end = j
                break
        del lines[i:end]
    # 2. blocks outside code
    out, fence, block = [], None, []

    def flush() -> None:
        if not block:
            return
        joined = " ".join(l.strip() for l in block)
        if bad(joined, public) is None:
            out.extend(block)
        else:
            first = block[0]
            prefix = re.match(r"^(\s*(?:[-*]|\d+\.)\s+|\s*)", first).group(1)
            body = joined[len(prefix.strip()):].strip() if prefix.strip() else joined
            kept = [s for s in SENTENCE_RE.split(body) if bad(s, public) is None]
            if kept:
                out.append(prefix + " ".join(kept))
        block.clear()

    for line in lines:
        m = FENCE_RE.match(line)
        if m or fence is not None:
            flush()
            if m:
                mark = m.group(2)
                if fence is None:
                    fence = mark[0] * len(mark)
                elif mark.startswith(fence) and line.strip() == mark:
                    fence = None
            out.append(line)
            continue
        if not line.strip() or line.lstrip().startswith("#"):
            flush()
            out.append(line)
            continue
        if line.lstrip().startswith("|"):
            flush()
            if bad(line, public) is None or re.match(r"^\s*\|[\s|:-]+\|\s*$", line):
                out.append(line)
            continue
        if re.match(r"^\s*(?:[-*]|\d+\.)\s+", line):
            flush()
        block.append(line)
    flush()
    return "\n".join(out)


# ------------------------------------------------------------------ Markdown -> MDX

LINK_RE = re.compile(r"(!?)\[((?:[^\[\]]|\[[^\]]*\])*)\]\(([^()\s]*(?:\([^()\s]*\)[^()\s]*)?)\)")
AUTOLINK_RE = re.compile(r"<(https?://[^>\s]+)>")
ROUTES: dict[str, str] = {}
SECTIONS: dict[str, str] = {}  # a source appended to another page as a section: the anchor of that section


@dataclass
class Ctx:
    src: str
    route: str


def mint_slug(text: str) -> str:
    """The anchor Mintlify gives a heading: lower case, quotes and backticks dropped, every other run of
    characters outside [a-z0-9] one hyphen."""
    text = re.sub(r"<[^>]+>|\{#[^}]*\}", "", text).lower()
    text = re.sub(r"[`'’*_]", "", text)
    return re.sub(r"[^a-z0-9]+", "-", text).strip("-")


def github_slug(text: str) -> str:
    text = re.sub(r"<[^>]+>", "", text).strip().lower()
    return re.sub(r"[^\w\- ]", "", text).replace(" ", "-")


_ANCHORS: dict[str, dict[str, str]] = {}


def translate_anchor(src: str, anchor: str) -> str:
    """A link's anchor written for the source file (a GitHub slug or an explicit <hN id>) as the site's anchor."""
    if src not in _ANCHORS:
        m: dict[str, str] = {}
        try:
            text = read(src)
        except OSError:
            text = ""
        for hid, title in re.findall(r'<h[1-6] id="([^"]+)">(.*?)</h[1-6]>', text):
            m[hid] = mint_slug(title)
        for _, _, title in headings(text.split("\n")):
            m.setdefault(github_slug(title), mint_slug(title))
        _ANCHORS[src] = m
    return _ANCHORS[src].get(anchor, anchor)


def resolve(ctx: Ctx, target: str) -> str | None:
    if re.match(r"^[a-z]+:", target) or target.startswith("//") or target.startswith("/"):
        return target
    if target.startswith("#"):
        return "#" + translate_anchor(ctx.src, target[1:])
    path, _, anchor = target.partition("#")
    full = posixpath.normpath(posixpath.join(posixpath.dirname(ctx.src), path)).rstrip("/")
    route = ROUTES.get(full)
    if route is None:
        return None
    route, _, frag = route.partition("#")
    if anchor and route == "/":
        return None  # the README's sections are not on the introduction page
    if anchor:
        src = full if os.path.isfile(os.path.join(ROOT, full)) else full + "/README.md"
        frag = translate_anchor(src, anchor)
    elif not frag:
        frag = SECTIONS.get(full, "")
    if route.startswith("/hardening"):
        return route
    if route == ctx.route:
        return "#" + frag if frag else route
    return route + ("#" + frag if frag else "")


def rewrite_links(line: str, ctx: Ctx) -> str:
    def repl(m: re.Match) -> str:
        bang, label, target = m.groups()
        dest = resolve(ctx, target)
        if dest is not None:
            return f"{bang}[{label}]({dest})"
        path = posixpath.normpath(posixpath.join(posixpath.dirname(ctx.src), target.partition("#")[0]))
        plain = label.strip("`")
        if plain in (path, posixpath.basename(path), path + "/", posixpath.basename(path) + "/"):
            return f"`{path}`"
        return f"{label} (`{path}`)"
    return LINK_RE.sub(repl, line)


def escape_line(line: str) -> str:
    out, i = [], 0
    while i < len(line):
        if line[i] == "`":
            run = re.match(r"`+", line[i:]).group(0)
            close = line.find(run, i + len(run))
            if close != -1:
                out.append(line[i: close + len(run)])
                i = close + len(run)
                continue
            out.append(run)
            i += len(run)
            continue
        j = line.find("`", i)
        j = len(line) if j == -1 else j
        seg = line[i:j].replace("{", "\\{").replace("}", "\\}")
        out.append(re.sub(r"<(?!/?(?:br)\b)", "&lt;", seg))
        i = j
    return "".join(out)


def md_to_mdx(text: str, ctx: Ctx) -> str:
    text = re.sub(r"<!--.*?-->\n?", "", text, flags=re.S)
    text = re.sub(r'<h([1-6]) id="[^"]*">(.*?)</h\1>', lambda m: "#" * int(m.group(1)) + " " + m.group(2), text)
    out, fence = [], None
    for line in text.split("\n"):
        m = FENCE_RE.match(line)
        if m:
            mark = m.group(2)
            if fence is None:
                fence = mark[0] * len(mark)
                if line.strip() == mark:
                    line = line + "text"
            elif mark.startswith(fence) and line.strip() == mark:
                fence = None
            out.append(line)
            continue
        if fence is not None:
            out.append(line)
            continue
        line = AUTOLINK_RE.sub(r"[\1](\1)", line)
        out.append(escape_line(rewrite_links(line, ctx)))
    return "\n".join(out)


def strip_h1(text: str) -> tuple[str, str]:
    m = re.search(r"^# (.+)\n+", text, re.M)
    if not m:
        return "", text
    return m.group(1).strip(), text[: m.start()] + text[m.end():]


def frontmatter(title: str, description: str, sidebar: str | None = None) -> str:
    q = lambda s: json.dumps(s, ensure_ascii=False)
    lines = ["---", f"title: {q(title)}"]
    if sidebar:
        lines.append(f"sidebarTitle: {q(sidebar)}")
    lines.append(f"description: {q(description)}")
    return "\n".join(lines + ["---"]) + "\n\n"


def slugify(text: str) -> str:
    text = re.sub(r"<[^>]+>", "", text)
    text = re.sub(r"[`*_]", "", text).strip().lower()
    text = re.sub(r"[^\w\- ]", "", text)
    return text.replace(" ", "-")


# ------------------------------------------------------------------ pages from sources


@dataclass
class Part:
    """A further source appended to a page as one section: its first heading is dropped and its headings move down
    one level under `## heading`."""
    src: str
    heading: str
    edit: Callable[[str], str] | None = None


@dataclass
class Page:
    src: str  # a Markdown source, or a hand-written template apps/docs/data/*.mdx.in (frontmatter and MDX body)
    dest: str
    description: str = ""
    title: str | None = None
    sidebar: str | None = None
    edit: Callable[[str], str] | None = None
    public: bool = True
    parts: list[Part] = field(default_factory=list)


def demote(text: str) -> str:
    """Every heading outside code one level down (Markdown and `<hN id>` headings)."""
    lines = text.split("\n")
    for i, _, _ in headings(lines):
        lines[i] = "#" + lines[i]
    out = "\n".join(lines)
    return re.sub(r'<h([1-5])( id="[^"]*">.*?)</h\1>', lambda m: f"<h{int(m.group(1)) + 1}{m.group(2)}</h{int(m.group(1)) + 1}>", out)


def parse_frontmatter(text: str, src: str) -> tuple[dict[str, str], str]:
    m = re.match(r"---\n(.*?)\n---\n", text, re.S)
    if not m:
        sys.exit(f"generate: {src}: no frontmatter")
    fm = {}
    for line in m.group(1).split("\n"):
        k, _, v = line.partition(":")
        v = v.strip()
        fm[k.strip()] = json.loads(v) if v.startswith('"') else v
    return fm, text[m.end():]


def unique_headings(dest: str, body: str) -> None:
    seen = collections.Counter(mint_slug(t) for _, _, t in headings(body.split("\n")))
    dup = sorted(k for k, n in seen.items() if n > 1)
    if dup:
        sys.exit(f"generate: {dest}: headings with the same anchor: {', '.join(dup)}")


def read(path: str) -> str:
    with open(os.path.join(ROOT, path), encoding="utf-8") as f:
        text = f.read()
    if re.search(r"^(<{7} |={7}$|>{7} )", text, re.M):
        sys.exit(f"generate: {path} holds merge-conflict markers")
    return text


class Out:
    def __init__(self) -> None:
        self.pages: dict[str, str] = {}
        self.cap_groups: set[str] = set()  # coverage rows with a section on the coverage page

    def emit(self, dest: str, src: str, title: str, description: str, body: str, sidebar: str | None = None) -> None:
        body = MODULE_RE.sub("github.com/OWNER/REPO", body)
        self.pages[dest] = frontmatter(title, description, sidebar) + (NOTE % src) + "\n\n" + body.strip() + "\n"

    def convert(self, page: Page) -> None:
        route = "/" + page.dest[:-4]
        if page.src.endswith(".mdx.in"):
            fm, body = parse_frontmatter(read(page.src), page.src)
            title, description, sidebar = fm["title"], fm["description"], fm.get("sidebarTitle")
        else:
            text = read(page.src)
            if page.edit:
                text = page.edit(text)
            text = scrub(text, page.public)
            title, body = strip_h1(text)
            body = md_to_mdx(body, Ctx(page.src, route))
            description, sidebar = page.description, page.sidebar
        taken = {mint_slug(t) for _, _, t in headings(body.split("\n"))}
        for part in page.parts:
            text = read(part.src)
            if part.edit:
                text = part.edit(text)
            _, pbody = strip_h1(scrub(text, page.public))
            pbody = re.sub(r'<h([1-6]) id="[^"]*">(.*?)</h\1>', lambda m: "#" * int(m.group(1)) + " " + m.group(2), pbody)
            lines = demote(pbody).split("\n")
            # a heading whose anchor the page already has is named with its section, and the source's links follow
            for i, _, t in headings(lines):
                if mint_slug(t) in taken:
                    new = f"{t} ({part.heading})"
                    translate_anchor(part.src, "")
                    _ANCHORS[part.src][github_slug(t)] = mint_slug(new)
                    lines[i] = lines[i].replace(t, new, 1)
                    t = new
                taken.add(mint_slug(t))
            taken.add(mint_slug(part.heading))
            body += f"\n\n## {part.heading}\n\n" + md_to_mdx("\n".join(lines), Ctx(part.src, route))
        unique_headings(page.dest, body)
        srcs = [page.src] + [p.src for p in page.parts]
        src = srcs[0] if len(srcs) == 1 else ", ".join(srcs[:-1]) + " and " + srcs[-1]
        self.emit(page.dest, src, page.title or title, description, body, sidebar)


