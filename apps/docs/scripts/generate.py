def build_index(out: Out, r: dict) -> None:
    """index.mdx: the hand-written template apps/docs/data/index.mdx.in with its figures filled in."""
    src = "apps/docs/data/index.mdx.in"
    text = read(src)
    vals = {k: (f"{v:,}" if isinstance(v, int) else str(v)) for k, v in r.items() if isinstance(v, (int, str))}
    vals.update({"known_defects_reproduced": str(r["known_defects"].get("reproduced", 0)),
                 "known_defects_total": str(sum(r["known_defects"].values())),
                 "sdk_names": ", ".join(r["sdks"][:-1]) + " and " + r["sdks"][-1],
                 "findings_total": str(sum(r["findings"]["state"].values())),
                 "findings_filed": str(r["findings"]["state"].get("filed", 0))})
    for k in ("scan_first", "scan_last"):
        vals[k] = f"{r[k]:,}"
    def fill(m: re.Match) -> str:
        if m.group(1) not in vals:
            sys.exit(f"generate: {src}: no value for @@{m.group(1)}@@")
        return vals[m.group(1)]
    out.pages["index.mdx"] = re.sub(r"@@(\w+)@@", fill, text)


