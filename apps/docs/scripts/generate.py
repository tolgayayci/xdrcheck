def cap_label(group: str) -> str:
    m = re.match(r"cap-0*(\d+)$", group)
    return f"CAP-{m.group(1)}" if m else group


COVERAGE = "/caps/overview"


def cap_href(group: str) -> str:
    """The link to a coverage row's section of the coverage page: its heading is the row's label."""
    return f"{COVERAGE}#{mint_slug(cap_label(group))}"


def entry_ledgers(e: dict) -> str:
    """Where the bytes come from: captured ledgers by network, or the source kind."""
    caught = sorted({(v["network"], v.get("ledger_seq")) for v in e["variants"]
                     if v["source"] in ("history", "history-archive") and v.get("ledger_seq")})
    if caught:
        return "captured: " + ", ".join(f"{n} {s}" for n, s in caught)
    kinds = sorted({v["source"] for v in e["variants"]})
    if not kinds:
        return "SDK call, no ledger" if e["kind"] in ("api", "strkey") else "—"
    names = {"local-core": "local stellar-core", "core-golden": "stellar-core golden", "synthetic": "recipe",
             "contract-code": "contract code"}
    return ", ".join(names.get(k, k) for k in kinds)


def entry_protocols(e: dict) -> str:
    intro = e["protocol"].get("introduced")
    emitted = sorted({v["protocol"] for v in e["variants"] if v.get("protocol")})
    s = str(intro) if intro is not None else "—"
    if emitted:
        s += " (bytes " + ", ".join(str(p) for p in emitted) + ")"
    return s


def md_cell(s: str) -> str:
    return s.replace("|", "\\|").replace("\n", " ")


