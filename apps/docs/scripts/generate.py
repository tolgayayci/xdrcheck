def edit_manifest(text: str) -> str:
    """docs/manifest.md names the golden-mirror check by its internal ID in places; the page names it in words.
    Each replacement is optional, so the source may drop the ID without breaking the generator."""
    text = re.sub(r" ?\(check AG-4\)", "", text)
    text = re.sub(r"What AG-4 checks", "What the golden-mirror check does", text)
    text = re.sub(r"\bno AG-4 variant row\b", "no golden-mirror variant row", text)
    text = re.sub(r"\bone AG-4 row\b", "one golden-mirror row", text)
    text = re.sub(r"(^|\n)(\s*(?:\d+\.\s+)?)AG-4\b", r"\1\2The golden-mirror check", text)
    return re.sub(r"\bAG-4\b", "the golden-mirror check", text)


def edit_authoring(text: str) -> str:
    src = "docs/authoring-entries.md"
    text = sub(text, r"\(check AG-4, `docs/manifest\.md`\n?\s*section 4\.7\)", "(`docs/manifest.md` section 4.7)", src)
    text = sub(text, r"YAML nests at most \d+ levels \(the parser's fixed limit\)", "YAML nests to a fixed limit of the parser",
               src)
    return text


