    gsrc, csrc, ysrc = "guide/indexer-hardening.mdx", "guide/checklist.mdx", "guide/claims.yaml"
    guide, checklist, claims = read(gsrc), read(csrc), read(ysrc)
    hs = [(lv, re.sub(r"\s*\{#([^}]+)\}$", "", t), (re.search(r"\{#([^}]+)\}$", t) or [None, ""])[1])
          for _, lv, t in headings(guide.split("\n"))]
    status = re.findall(r"^\s*reviewer_status:\s*(\w+)", claims, re.M)
    kinds = re.findall(r"^  kind:\s*(\w+)", claims, re.M)
    if not status:
        sys.exit(f"generate: {ysrc}: no reviewer_status found")
    counts = {s: status.count(s) for s in ("unreviewed", "confirmed", "corrected", "disputed")}
    reviewed = counts["confirmed"] + counts["corrected"]
    rows = re.findall(r"^\| VF-\d+[a-z]? \| [^|]+\| [^|]+\| (validated|partially validated|passed through) \|", guide, re.M)
