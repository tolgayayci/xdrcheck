def update_nav() -> str:
    """docs.json as it stands, normalised; the navigation is written by hand (every page is one entry)."""
    with open(os.path.join(SITE, "docs.json"), encoding="utf-8") as f:
        cfg = json.load(f)
    return json.dumps(cfg, indent=2, ensure_ascii=False) + "\n"


def finding_refs() -> set[tuple[str, str]]:
    refs = set()
    for f in glob.glob(os.path.join(ROOT, "findings", "**", "*.json"), recursive=True):
        try:
            s = open(f, encoding="utf-8").read()
        except OSError:
            continue
        for m in re.finditer(r"github\.com/[\w.-]+/([\w.-]+)/(?:issues|pull|security/advisories)/([\w-]+)", s):
            refs.add((m.group(1), m.group(2)))
    return refs - KNOWN_DEFECT_ITEMS


def scan(pages: dict[str, str], refs: set[tuple[str, str]]) -> list[str]:
    problems = []
    for dest, text in sorted(pages.items()):
        public = dest not in FINDINGS_PAGES
        for n, line in enumerate(text.split("\n"), 1):
            hit = bad(line, public)
            if hit:
                problems.append(f"apps/docs/{dest}:{n}: {hit!r}: {line.strip()[:140]}")
            if public:
                for repo, num in refs:
                    if re.search(r"\b%s(?:#|/issues/|/pull/|/security/advisories/)%s\b" % (re.escape(repo), re.escape(num)), line):
                        problems.append(f"apps/docs/{dest}:{n}: upstream item of a finding ({repo}#{num})")
    return problems


def site_pages() -> dict[str, str]:
    out = {}
    for f in glob.glob(os.path.join(SITE, "**", "*.mdx"), recursive=True):
        if "/node_modules/" in f:
            continue
        out[os.path.relpath(f, SITE)] = open(f, encoding="utf-8").read()
    return out


def page_anchors(text: str) -> set[str]:
    """The anchors of an MDX page: its headings (outside code) as Mintlify slugs them."""
    return {mint_slug(t) for _, _, t in headings(text.split("\n"))}


def nav_pages(cfg_text: str) -> list[str]:
    cfg = json.loads(cfg_text)
    out = []
    for tab in cfg["navigation"]["tabs"]:
        for g in tab["groups"]:
            out += [p for p in g["pages"] if isinstance(p, str)]
    return out


def capture_help(bin_dir: str) -> None:
    os.makedirs(os.path.join(DATA, "help"), exist_ok=True)
    for role, subs in HELP_CAPTURE.items():
        for s in subs:
            cmd = [os.path.join(bin_dir, TOOLS[role])] + ([s] if s else []) + ["--help"]
            p = subprocess.run(cmd, capture_output=True, text=True)
            if p.returncode != 0:
                sys.exit(f"generate: {' '.join(cmd)} failed: {p.stderr.strip()}")
            with open(os.path.join(DATA, "help", f"{role}{'-' + s if s else ''}.txt"), "w", encoding="utf-8") as f:
                f.write(p.stdout.rstrip() + "\n")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true", help="fail when a generated page is stale or any page breaks a rule")
    ap.add_argument("--capture-help", metavar="BIN_DIR", help="refresh apps/docs/data/help/ from built binaries first")
    args = ap.parse_args()
    if args.capture_help:
        capture_help(args.capture_help)

    add_finding_refs()
    out = Out()
    for page in PAGES:
        out.convert(page)
    build_cli(out)
    build_lint(out)
    stats = build_caps(out)
    build_mainnet_scan(out)
    stats["results"] = build_results(out)
    build_entry_walk(out)
    build_hardening(out)
    build_index(out, stats["results"])
    nav = update_nav()

    stale = []
    files = dict(out.pages)
    files["docs.json"] = nav
    for dest, text in sorted(files.items()):
        path = os.path.join(SITE, dest)
        old = open(path, encoding="utf-8").read() if os.path.exists(path) else None
        if old == text:
            continue
        if args.check:
            stale.append(dest)
            sys.stdout.writelines(difflib.unified_diff((old or "").splitlines(True), text.splitlines(True), dest, dest, n=1))
        else:
            os.makedirs(os.path.dirname(path), exist_ok=True)
            with open(path, "w", encoding="utf-8") as f:
                f.write(text)

    pages = site_pages()
    pages.update(out.pages)
    problems = scan(pages, finding_refs())
    missing = [p for p in nav_pages(nav) if p + ".mdx" not in pages]
    routes = {"/" + p[:-4] for p in pages} | {"/"}
    routes |= {r[: -len("/index")] for r in routes if r.endswith("/index")}
    anchors = {"/" + p[:-4]: page_anchors(t) for p, t in pages.items()}
    anchors["/"] = anchors.get("/index", set())
    for dest, text in sorted(pages.items()):
        for m in re.finditer(r"\]\((/[^)#\s]*)(#[^)\s]*)?\)|href=\"(/[^\"#]*)(#[^\"]*)?\"|\]\((#[^)\s]+)\)", text):
            if m.group(5):
                route, anchor = "/" + dest[:-4], m.group(5)[1:]
            else:
                route = (m.group(1) or m.group(3)).rstrip("/") or "/"
                anchor = (m.group(2) or m.group(4) or "#")[1:]
            if route not in routes and route != "/index":
                problems.append(f"apps/docs/{dest}: link to {route}, which has no page")
            elif anchor and anchor not in anchors.get(route, set()):
                problems.append(f"apps/docs/{dest}: link to {route}#{anchor}, which has no such heading")
    orphans = sorted(p[:-4] for p in pages if p[:-4] not in set(nav_pages(nav)))
    for p in problems:
        print(p, file=sys.stderr)
    for p in missing:
        print(f"docs.json names {p}, which has no page", file=sys.stderr)
    for p in orphans:
        print(f"apps/docs/{p}.mdx is in no navigation group", file=sys.stderr)
    if stale:
        print(f"generate: {len(stale)} generated file(s) out of date; run apps/docs/scripts/generate.py", file=sys.stderr)
    caps = sum(1 for g in stats["groups"] if g.startswith("cap-"))
    print(f"generate: {len(out.pages)} generated pages; coverage rows {stats['rows']} ({caps} CAPs), entries listed "
          f"{len(stats['entries'])} of {stats['entries_total']}, entries with prevalence "
          f"{len(stats['entries_with_prevalence'])}, entries held back {len(stats['held'])}")
    return 1 if (stale or problems or missing or orphans) else 0


if __name__ == "__main__":
    sys.exit(main())
