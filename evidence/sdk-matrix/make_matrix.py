"""Builds results/matrix.md from vectors/vectors.json and results/*.jsonl. Usage: python3 -I make_matrix.py

With XCC_OVERLAY set, the result files under <overlay>/evidence/sdk-matrix/results/ are read as well and the table
is written there instead."""
import glob, json, os
os.chdir(os.path.dirname(os.path.abspath(__file__)))
OVERLAY = os.path.join(os.environ["XCC_OVERLAY"], "evidence", "sdk-matrix") if os.environ.get("XCC_OVERLAY") else None
DIRS = ["results"] + ([os.path.join(OVERLAY, "results")] if OVERLAY else [])


def rows(name):
    """The JSON rows of results/<name> and, with the overlay, of its overlay counterpart."""
    out = []
    for d in DIRS:
        p = os.path.join(d, name)
        if os.path.exists(p):
            out += [json.loads(l) for l in open(p) if l.strip()]
    return out


V = json.load(open("vectors/vectors.json"))
order = [("js", ["16.3.0", "16.3.1", "16.4.1", "17.2.0", "17.2.1", "17.3.0", "17.4.0"]), ("go", ["v0.7.1", "v0.7.2", "v0.7.3", "v0.8.0"]),
         ("rust", [f"{v} {m}" for v in ["28.0.0", "28.0.1", "30.0.0"] for m in ["Limits{500,len}", "Limits::none()"]]),
         ("python", ["17.0.0", "17.0.1"])]
cols, R = [], {}
for sdk, vers in order:
    for ver in vers:
        cols.append((sdk, ver))
for name in sorted({os.path.basename(fn) for d in DIRS for fn in glob.glob(os.path.join(d, "*.jsonl"))}):
    if "depth_boundaries" in name or "extra_" in name:
        continue
    for d in rows(name):
        R[(d["sdk"], d["version_label"], d["vector"])] = d

def expected(v):
    a = v["expect"]["accept"]
    val = v["expect"].get("value")
    s = {True: "accept", False: "reject", "either": "accept-exact or reject", "p30": "accept if P30 schema, else reject", "info": "(boundary)"}[a]
    if val is not None and a is not False:
        s += f" `{val[:24]}{'…' if len(val) > 24 else ''}`"
    return s

def verdict(v, d):
    o, a = d["outcome"], v["expect"]["accept"]
    if o in ("n/a", "missing"): return None
    if o == "crash": return False
    if a == "info": return None
    if a == "p30": a = bool(d.get("p30"))
    if a is True: return o == "ok"
    if a is False: return o == "reject"
    return o in ("ok", "reject")

def cell(v, d):
    if d is None: return "–"
    o = {"ok": "ok", "reject": "rej", "wrong": "WRONG", "crash": "CRASH", "n/a": "n/a"}.get(d["outcome"], d["outcome"])
    vd = verdict(v, d)
    return f"**{o}**" if vd is False else o

short = {"js": "js", "go": "go", "rust": "rs", "python": "py"}
def colname(c):
    sdk, ver = c
    ver = ver.replace("Limits{500,len}", "L500").replace("Limits::none()", "none")
    return f"{short[sdk]} {ver}"

out = ["# SDK divergence matrix (generated by make_matrix.py — do not edit)", "",
       "Cell = observed outcome: `ok` accepted (value matches expectation), `rej` clean error, `WRONG` accepted but wrong value or accepted invalid input, "
       "`CRASH` process abort / panic / stack overflow, `n/a` API does not exist. **Bold** = diverges from the expected column. "
       "`rs … L500` = `Limits{depth:500,len:input}`, `none` = `Limits::none()`. Expected values and justifications are in `vectors/vectors.json` (`why`).", ""]
groups = {1: "1. Issuer ordering", 2: "2. 64-bit IDs through builders", 3: "3. Decode→encode identity", 4: "4. Map key collisions (native)",
          5: "5. Map key order on encode", 6: "6. XDR strictness", 7: "7. Non-UTF-8 bytes", 8: "8. Depth (nested ScVal Vec)", 9: "9. Strkey", 10: "10. Protocol 30 LCM"}
for gnum, gname in groups.items():
    vs = [v for v in V if v["group"] == gnum]
    out += [f"## {gname}", "", "| vector | level | expected | " + " | ".join(colname(c) for c in cols) + " |",
            "|---|---|---|" + "---|" * len(cols)]
    for v in vs:
        out.append(f"| {v['id']} {v['title'][:60]} | {v['level']} | {expected(v)} | " + " | ".join(cell(v, R.get((c[0], c[1], v["id"]))) for c in cols) + " |")
    out += ["", "Details (one line per distinct outcome):", ""]
    for v in vs:
        seen = {}
        for c in cols:
            d = R.get((c[0], c[1], v["id"]))
            if not d: continue
            det = (d.get("detail") or "").replace("\n", " ").replace("|", "/")
            got = d.get("got")
            if d["outcome"] in ("ok", "wrong") and got is not None:
                det = (f"got `{str(got)[:90]}` " + det).strip()
            key = (d["outcome"], det[:170])
            seen.setdefault(key, []).append(colname(c))
        lines = [f"  - {o}: {det} — {', '.join(cs)}" for (o, det), cs in seen.items()]
        out.append(f"- **{v['id']}**")
        out += lines
    out.append("")
# depth boundaries
if rows("depth_boundaries.jsonl"):
    out += ["## 8b. Exact depth boundary (bisected, default decode entry point)", "", "| SDK | version | max N decoded | first N rejected | error / note |", "|---|---|---|---|---|"]
    for d in rows("depth_boundaries.jsonl"):
        note = d.get("fail_detail", "") or d.get("n100000", "")
        out.append(f"| {d['sdk']} | {d['version']} | {d['max_ok']} | {d['first_fail'] if d['first_fail'] is not None else '—'} | {note[:110].replace('|', '/')} |")
    out.append("")
if rows("extra_as_limit.jsonl"):
    out += ["## 6h. Memory vectors under an address-space cap (`prlimit --as=1GiB`)", "", "| SDK | version | vector | outcome | detail |", "|---|---|---|---|---|"]
    for d in rows("extra_as_limit.jsonl"):
        out.append(f"| {d['sdk']} | {d['version_label']} | {d['vector']} | {d['outcome']} | {(d.get('detail') or '')[:100].replace('|', '/')} |")
target = os.path.join(OVERLAY or ".", "results", "matrix.md")
open(target, "w").write("\n".join(out) + "\n")
print("wrote", target, len(out), "lines")
