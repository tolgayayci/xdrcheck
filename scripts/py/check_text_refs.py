#!/usr/bin/env python3
"""Check that what the hand-written texts name exists in the tree.

`check_guide_entries.py` does this for the guide's corpus citations; this check does it for the rest of the
hand-written text: README.md, CONTRIBUTING.md, CHANGELOG.md, docs/*.md, findings/README.md, findings/REPORT-*.md,
every tracked README under evidence/, examples/, packages/, lint/, go/, crates/, drivers/ and apps/, and the
hand-written pages of apps/docs (every .mdx page without the generator's "Generated by" note, and the page
templates apps/docs/data/*.mdx.in). In those files it checks:

- corpus entries: every backticked `group/name` token whose group is a corpus group (a row of corpus/plan.json)
  names an entry of corpus/index.json, the base of one (`group/name` for `group/name.member`), or, with `*`, a
  glob that matches at least one entry (`*` crosses `/`); a token that names only a planned row is reported too;
- finding records: every `F-nnnn` has a directory findings/F-nnnn;
- make targets: every `make <target>` inside backticks or a fenced code block is a target of the Makefile
  (read from `make -pRrq`, so undocumented targets count);
- commands: every `xdrcheck`, `xdrcheck-corpus` or `xdrlint` command inside backticks or a fenced code block names
  a command the generated help blocks of docs/cli.md hold, and each `--flag` on it appears in that command's help
  (or in the help of one of its subcommands); docs/cli.md itself is kept equal to the help by check_cli_reference.py;
- links: every relative Markdown link of a .md file resolves to a file or directory of the tree (anchors are not
  checked; the documentation site's own links are checked by apps/docs/scripts/generate.py --check).

Usage: check_text_refs.py [--root DIR]. Exit 1 on any failure."""
import fnmatch, glob, json, os, re, subprocess, sys

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
SKIP = {"docs/ci-timings.md"}  # generated from CI measurements, checked by its own tool
# Files whose links are written relative to where a generator copies them (lint/docs/src/README.md becomes
# lint/docs/README.md), so their links are checked in the copy.
LINKS_ELSEWHERE = ("lint/docs/src/",)
# docs/entry-ids.md defines the ID grammar: its examples show the form of IDs, including planned family members and
# a hypothetical census ledger, and are not citations of entries.
ENTRY_EXAMPLES = {"docs/entry-ids.md"}
# Finding IDs the text names on purpose without a record: a documented gap in the public sequence and the first ID
# of the range the private overlay uses (findings/README.md, "IDs").
FINDING_NAMED = {"F-0031", "F-5000"}
README_DIRS = ("evidence/", "examples/", "packages/", "lint/", "go/", "crates/", "drivers/", "apps/")

CODE_SPAN = re.compile(r"`([^`\n]+)`")
FENCE = re.compile(r"^\s*```")
ENTRY = re.compile(r"^([a-z0-9]+(?:-[a-z0-9]+)*)/([a-z0-9*]+(?:[.*-][a-z0-9*]*)*)$")
FINDING = re.compile(r"(?<![\w-])F-(\d{4})(?!\d)")
MAKE = re.compile(r"(?:^|&&|;|\||\(|^\$)\s*(?:\$\s+)?(?:[A-Z_]+=\S+\s+)*make\s+((?:[A-Z_]+=\S+\s+)*)([a-z][a-z0-9-]*)")
TOOL = re.compile(r"(?<![\w/=-])(?:bin/|go/bin/|target/release/)?(xdrcheck-corpus|xdrcheck|xdrlint)((?:\s+[^\s|;&()]+)*)")
LINK = re.compile(r"\]\(([^)\s]+)\)")
HELP_HEAD = re.compile(r"^#### `((?:xdrcheck-corpus|xdrcheck|xdrlint)(?: [\w-]+)*) (?:--help|-h)`")


def tracked(root):
    out = subprocess.check_output(["git", "ls-files"], cwd=root, text=True).split("\n")
    return [p for p in out if p]


def files(root):
    names = []
    for p in tracked(root):
        if p in SKIP:
            continue
        base = os.path.basename(p)
        if p in ("README.md", "CONTRIBUTING.md", "CHANGELOG.md", "findings/README.md") or re.fullmatch(r"apps/docs/data/[^/]+\.mdx\.in", p):
            names.append(p)
        elif re.fullmatch(r"docs/[^/]+\.md", p) or re.fullmatch(r"findings/REPORT-[^/]+\.md", p):
            names.append(p)
        elif base.startswith("README") and p.startswith(README_DIRS) and not p.startswith(("findings/F-",)):
            names.append(p)
        elif p.startswith("apps/docs/") and p.endswith(".mdx"):
            with open(os.path.join(root, p), encoding="utf-8") as f:
                if "Generated by" not in f.read(2000):
                    names.append(p)
    return sorted(set(names))


def corpus(root):
    with open(os.path.join(root, "corpus", "index.json"), encoding="utf-8") as f:
        ids = {e["id"] for e in json.load(f)["entries"]}
    with open(os.path.join(root, "corpus", "plan.json"), encoding="utf-8") as f:
        planned = {r["id"] for r in json.load(f)}
    return ids, planned, {i.split("/")[0] for i in ids | planned}


def make_targets(root):
    p = subprocess.run(["make", "-pRrq", "-f", "Makefile"], cwd=root, capture_output=True, text=True)
    targets = set()
    for line in p.stdout.split("\n"):
        m = re.match(r"^([a-zA-Z0-9][\w.-]*):(?!=)", line)
        if m:
            targets.add(m.group(1))
    return targets


def help_sections(root):
    """{command: help text} from docs/cli.md's generated help blocks."""
    sections, cur, buf = {}, None, []
    with open(os.path.join(root, "docs", "cli.md"), encoding="utf-8") as f:
        for line in f:
            m = HELP_HEAD.match(line)
            if m or line.startswith("<!-- END GENERATED"):
                if cur:
                    sections[cur] = "".join(buf)
                cur, buf = (m.group(1) if m else None), []
            elif cur:
                buf.append(line)
    if cur:
        sections[cur] = "".join(buf)
    return sections


def code_texts(text):
    """(line number, text) of every backticked span and every line inside a fenced block."""
    inside = False
    for n, line in enumerate(text.split("\n"), 1):
        if FENCE.match(line):
            inside = not inside
            continue
        if inside:
            yield n, line
        else:
            for m in CODE_SPAN.finditer(line):
                yield n, m.group(1)


def check_entry(tok, ids, planned, groups):
    m = ENTRY.match(tok)
    if not m or m.group(1) not in groups:
        return None
    if "*" in tok:
        pat = tok.replace("*", "\x00")
        rx = re.compile("^" + re.escape(pat).replace("\x00", ".*") + "$")
        return None if any(rx.match(i) for i in ids) else f"glob {tok!r} matches no entry of corpus/index.json"
    if tok in ids or any(i.startswith(tok + ".") for i in ids):
        return None
    if tok in planned:
        return f"{tok!r} is a planned row of corpus/plan.json with no entry in corpus/index.json"
    return f"{tok!r} is not an entry of corpus/index.json"


def check_command(words, sections):
    """words: the command's tokens, the tool first. Returns a problem or None."""
    tool = words[0]
    path, i = tool, 1
    while i < len(words) and re.fullmatch(r"[a-z][a-z0-9-]*", words[i]) and f"{path} {words[i]}" in sections:
        path += " " + words[i]
        i += 1
    if path not in sections:
        return None if tool == "xdrlint" else f"`{tool}` has no help block in docs/cli.md"
    if i < len(words) and re.fullmatch(r"[a-z][a-z0-9-]*", words[i]) and tool != "xdrlint":
        # A command the help lists but docs/cli.md has no block for (`xdrcheck data fetch`, `scan run`): its flags
        # are not in the page, so only the command name is checked.
        if not re.search(r"^\s+" + re.escape(words[i]) + r"\b", sections[path], re.M):
            return f"`{path} {words[i]}`: no such command in `{path} --help`" if path == tool else None
        return None
    if path == "xdrcheck replay" and ({"--target", "--rig", "--issue"} & set(words)):
        return None  # the target and rig forms have their own help (`xdrcheck replay --target T --help`)
    helps = "".join(v for k, v in sections.items() if k == path or k.startswith(path + " "))
    for w in words[i:]:
        m = re.fullmatch(r"(--?[a-z][a-z0-9-]*)(?:=.*)?", w)
        if not m or m.group(1) in ("--help", "-h"):
            continue
        name = m.group(1).lstrip("-")
        if not re.search(r"(?<![\w-])--?" + re.escape(name) + r"(?![\w-])", helps):
            return f"`{path}`: flag --{name} is not in its help"
    return None


def problems(root=ROOT):
    ids, planned, groups = corpus(root)
    targets = make_targets(root)
    sections = help_sections(root)
    bad = []
    names = files(root)
    for rel in names:
        with open(os.path.join(root, rel), encoding="utf-8") as f:
            text = f.read()
        for n, line in enumerate(text.split("\n"), 1):
            for m in FINDING.finditer(line):
                if "F-" + m.group(1) in FINDING_NAMED:
                    continue
                if not os.path.isdir(os.path.join(root, "findings", "F-" + m.group(1))):
                    bad.append(f"{rel}:{n}: F-{m.group(1)} has no record under findings/")
            for m in CODE_SPAN.finditer(line):
                for tok in ([] if rel in ENTRY_EXAMPLES else re.split(r"[\s,]+", m.group(1))):
                    tok = tok.strip("()[]:;'\"")
                    p = check_entry(tok, ids, planned, groups)
                    if p:
                        bad.append(f"{rel}:{n}: {p}")
            if rel.endswith(".md") and not rel.startswith(LINKS_ELSEWHERE):
                for m in LINK.finditer(line):
                    target = m.group(1).split("#")[0]
                    if not target or re.match(r"^[a-z][a-z0-9+.-]*:", target) or target.startswith("/"):
                        continue
                    if not os.path.exists(os.path.normpath(os.path.join(root, os.path.dirname(rel), target))):
                        bad.append(f"{rel}:{n}: link {target!r} does not resolve")
        for n, code in code_texts(text):
            for m in MAKE.finditer(code):
                t = m.group(2)
                if t not in targets:
                    bad.append(f"{rel}:{n}: `make {t}` is not a make target")
            for m in TOOL.finditer(code):
                if re.search(r"(?:^|\s)--?[\w-]+\s+$", code[:m.start()]):
                    continue  # the binary is another command's flag value (`--xdrcheck-corpus target/release/...`)
                words = [m.group(1)] + m.group(2).split()
                p = check_command(words, sections)
                if p:
                    bad.append(f"{rel}:{n}: {p}")
    return bad, len(names)


def main(argv):
    root = ROOT
    if len(argv) == 2 and argv[0] == "--root":
        root = os.path.abspath(argv[1])
    elif argv:
        sys.exit(__doc__)
    bad, n = problems(root)
    print(f"text refs: entries, findings, make targets, commands and links checked in {n} hand-written files")
    for b in bad:
        print("FAIL", b)
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
